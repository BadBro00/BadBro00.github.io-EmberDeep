def parse(idx: int) -> dict:
    """Parse level ASCII into grid + entity spawn lists (tile coords)."""
    lv = LEVELS[idx]
    grid = [list(r) for r in lv["map"]]
    w = max(len(r) for r in grid)
    for r in grid:
        while len(r) < w:
            r.append(".")
    ents = {"spawn": None, "beacon": None, "coins": [], "hearts": [], "keys": [],
            "doors": [], "rocks": [], "crawlers": [], "hoppers": [], "bats": [],
            "turrets": [], "checks": [], "signs": {}, "mplats_h": [], "mplats_v": [],
            "springs": [], "boss": None, "maxhp": [], "giver": None}
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch == "P":
                ents["spawn"] = (x, y); row[x] = "."
            elif ch == "E":
                ents["beacon"] = (x, y); row[x] = "."
            elif ch == "C":
                ents["coins"].append((x, y)); row[x] = "."
            elif ch == "H":
                ents["hearts"].append((x, y)); row[x] = "."
            elif ch == "K":
                ents["keys"].append((x, y)); row[x] = "."
            elif ch == "A":
                ents["maxhp"].append((x, y)); row[x] = "."
            elif ch == "1":
                ents["crawlers"].append((x, y)); row[x] = "."
            elif ch == "2":
                ents["hoppers"].append((x, y)); row[x] = "."
            elif ch == "3":
                ents["bats"].append((x, y)); row[x] = "."
            elif ch == "4":
                ents["turrets"].append((x, y)); row[x] = "."
            elif ch == "T":
                ents["checks"].append((x, y)); row[x] = "."
            elif ch == "N":
                ents["signs"][(x, y)] = lv["signs"].get((x, y), "..."); row[x] = "N"
            elif ch == "G":
                ents["giver"] = (x, y); row[x] = "G"
            elif ch == "M":
                ents["mplats_h"].append((x, y)); row[x] = "."
            elif ch == "V":
                ents["mplats_v"].append((x, y)); row[x] = "."
            elif ch == "U":
                ents["springs"].append((x, y)); row[x] = "."
            elif ch == "O":
                ents["boss"] = (x, y); row[x] = "."
    # keep D/R in grid (solid), doors/rocks tracked separately
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch == "D":
                ents["doors"].append((x, y))
            elif ch == "R":
                ents["rocks"].append((x, y))
    return {"grid": grid, "w": w, "h": len(grid), "ents": ents, "meta": lv}


def validate(idx: int) -> list[str]:
    """Return list of problems (empty = ok). Used by tests."""
    errs = []
    d = parse(idx)
    e, g = d["ents"], d["grid"]
    if e["spawn"] is None:
        errs.append("no spawn")
    if e["beacon"] is None:
        errs.append("no beacon")
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch not in ".#=BRDS~N G":
                errs.append(f"bad char {ch!r} at {(x, y)}")
    # doors need a key somewhere in this or earlier level
    if e["doors"] and not e["keys"]:
        errs.append("door without key")
    return errs
