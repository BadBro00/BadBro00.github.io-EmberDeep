def text_size(s: str, scale: int = 1) -> tuple[int, int]:
    return (len(s) * 6 - 1) * scale if s else (0, 0), 7 * scale


def draw_text(surf: pygame.Surface, s: str, x: int, y: int,
              color: tuple = (235, 240, 255), scale: int = 1) -> None:
    s = s.upper().replace("’", "'")
    cx = x
    for ch in s:
        g = _FONT.get(ch, _FONT["?"])
        for ry, row in enumerate(g):
            for rx, bit in enumerate(row):
                if bit == "1":
                    if scale == 1:
                        if 0 <= cx + rx < surf.get_width() and 0 <= y + ry < surf.get_height():
                            surf.set_at((cx + rx, y + ry), color)
                    else:
                        surf.fill(color, (cx + rx * scale, y + ry * scale, scale, scale))
        cx += 6 * scale
