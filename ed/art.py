def _surf(rows: list[str]) -> pygame.Surface:
    h, w = len(rows), max(len(r) for r in rows)
    s = pygame.Surface((w, h), pygame.SRCALPHA)
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch in (".", " "):
                continue
            s.set_at((x, y), PAL.get(ch, (255, 0, 255)))
    return s


_CACHE: dict[str, pygame.Surface] = {}


def sprite(name: str) -> pygame.Surface:
    if name in _CACHE:
        return _CACHE[name]
    table = {
        "p1": P1, "p2": P2, "pj": PJ, "cr1": CR1, "cr2": CR2,
        "ho": HO1, "bat1": BAT1, "bat2": BAT2, "tur": TUR,
        "coin1": COIN1, "coin2": COIN2, "heart": HEART, "key": KEY,
        "spike": SPIKE, "torch": TORCH1, "beacon": BEACON,
        "sign": SIGN, "ghost": GHOST, "boss": BOSS1,
    }
    s = _surf(table[name])
    _CACHE[name] = s
    return s


def tile(ch: str, t: int = 0) -> pygame.Surface:
    """Procedural 16x16 tile. t = anim tick for lava."""
    key = f"tile{ch}{t & 1}"
    if key in _CACHE:
        return _CACHE[key]
    s = pygame.Surface((16, 16))
    hsh = lambda x, y: (x * 73 + y * 149 + ord(ch)) % 7
    if ch == "#":  # dirt
        s.fill((88, 58, 44))
        for y in range(16):
            for x in range(16):
                if hsh(x, y) == 0:
                    s.set_at((x, y), (70, 45, 35))
        for x in range(16):
            s.set_at((x, 0), (110, 75, 55))
    elif ch == "=":  # grass top
        s.fill((88, 58, 44))
        s.fill((75, 175, 85), (0, 0, 16, 6))
        s.fill((110, 220, 120), (0, 0, 16, 2))
        for x in range(0, 16, 3):
            s.set_at((x, 6), (75, 175, 85))
    elif ch == "B":  # brick
        s.fill((120, 70, 70))
        for y in (0, 7, 15):
            for x in range(16):
                s.set_at((x, y), (70, 40, 45))
        for x in (7, 15):
            for y in range(16):
                s.set_at((x, y), (70, 40, 45))
    elif ch == "R":  # breakable rock (cracked)
        s.fill((110, 110, 130))
        for x in range(16):
            s.set_at((x, 0), (60, 60, 80)); s.set_at((x, 15), (60, 60, 80))
        for i in range(6):
            s.set_at((3 + i, 3 + i), (60, 60, 80))
            s.set_at((12 - i, 4 + i), (200, 200, 220))
    elif ch == "D":  # door (locked)
        s.fill((90, 55, 30))
        s.fill((130, 85, 45), (3, 1, 10, 14))
        s.set_at((11, 8), (250, 215, 90)); s.set_at((11, 9), (250, 215, 90))
    elif ch == "~":  # lava
        c = (250, 120, 30) if (t & 1) == 0 else (250, 170, 50)
        s.fill(c)
        for x in range(0, 16, 2):
            s.set_at((x, 4 + (x + t) % 8), (180, 60, 20))
    elif ch == "N":  # sign backplate (sign sprite drawn over)
        s.fill((0, 0, 0))
    elif ch == "G":
        s.fill((0, 0, 0))
    else:
        s.fill((0, 0, 0))
    _CACHE[key] = s
    return s


